// Render text onto a pixel grid
// Returns 2D array [y][x] with pixel values
function renderText(text, fontName, spacing, bold) {
  const font = FONTS[fontName] || FONTS['5x7'];
  const charH = font.height;
  const charW = font.width;
  const sp = (spacing !== undefined ? spacing : font.spacing);
  const isBold = bold || font.bold;

  let totalW = 0;
  for (const ch of text) {
    const colData = font.chars[ch] || font.chars[' '] || [];
    totalW += (colData.length || charW) + sp + (isBold ? 1 : 0);
  }
  if (totalW > 0) totalW -= sp;

  const grid = [];
  for (let y = 0; y < charH; y++) {
    grid.push(new Array(totalW).fill(0));
  }

  let x = 0;
  for (const ch of text) {
    const colData = font.chars[ch] || font.chars[' '] || new Array(charW).fill(0);
    for (let col = 0; col < colData.length; col++) {
      const byte = colData[col];
      for (let bit = 0; bit < charH; bit++) {
        if (byte & (1 << bit)) {
          if (x + col < totalW) grid[bit][x + col] = 1;
          if (isBold && x + col + 1 < totalW) grid[bit][x + col + 1] = 1;
        }
      }
    }
    x += colData.length + (isBold ? 1 : 0) + sp;
  }

  return { grid, width: totalW, height: charH };
}
